import { readFileSync } from 'node:fs';
import type { NetworkFixture, Recording } from './types.ts';
import { REDACTED } from './privacy.ts';
import { fixtureKey } from './safety.ts';

function toJson(value: unknown): string {
  // JSON serialization prevents captured user data from becoming executable code.
  return JSON.stringify(value, null, 2);
}

/** Fingerprints only matter when one endpoint has fixtures recorded for different requests. */
function needsFingerprints(network: NetworkFixture[]): boolean {
  const first = new Map<string, string | undefined>();
  return network.some(fixture => {
    const key = fixtureKey(fixture.method, fixture.path, fixture.origin);
    if (!first.has(key)) { first.set(key, fixture.match); return false; }
    return first.get(key) !== fixture.match;
  });
}

/** The spec fingerprints requests with GhostBug's own redaction code, so it always agrees with the recorder. */
function redactSource(): string {
  // src/redact.ts in development; the build copies it to dist/redact.source.ts.
  for (const file of ['./redact.ts', './redact.source.ts']) {
    try {
      return readFileSync(new URL(file, import.meta.url), 'utf8').replace(/^import .*\n/gm, '').replace(/^export /gm, '').trim();
    } catch { /* try the next location */ }
  }
  throw Error('GhostBug installation is incomplete: redact.ts not found. Rebuild with npm run build.');
}

/** Emit an editable @playwright/test spec, without requiring an AI API key. */
export function generateSpec(recording: Recording, assertion?: string): string {
  const expectedText = assertion ?? recording.expect?.text;
  if (!expectedText?.trim()) throw Error('Missing expected outcome. Use --expect-text "Expected UI message"');
  const start = new URL(recording.startUrl);
  const path = start.pathname; // Intentionally discard query/hash; may include secrets.
  const note = recording.actions.some(a => a.type === 'fill' && a.value === REDACTED);
  const fingerprints = needsFingerprints(recording.network);
  return `// Auto-generated by GhostBug. Review the file and fixtures before sharing.\n` +
`// IMPORTANT: Run against a local/staging application, NOT production.\n` +
`import { test, expect } from '@playwright/test';\n` +
(fingerprints ? `import { createHash } from 'node:crypto';\n` : '') + `\n` +
`const originalOrigin = ${toJson(start.origin)};\n` +
`const startPath = ${toJson(path)};\n` +
`type GhostBugAction = { type: 'click'; selector: string } | { type: 'fill'; selector: string; value: string } | { type: 'check'; selector: string; checked: boolean };\n` +
`type GhostBugResponse = { method: string; path: string; origin?: string; status: number; contentType: string; body: string; match?: string };\n` +
`const actions: GhostBugAction[] = ${toJson(recording.actions)};\n` +
`const recordedResponses: GhostBugResponse[] = ${toJson(recording.network)};\n` +
`const expectedText = ${toJson(expectedText)};\n\n` +
(fingerprints ? `// Request fingerprints: copied from GhostBug so they match the recorded "match" values.\n${redactSource()}\n\n` : '') +
`test(${toJson(recording.name)}, async ({ page }) => {\n` +
`  const baseUrl = process.env.GHOSTBUG_BASE_URL || originalOrigin;\n` +
`  const base = new URL(baseUrl);\n` +
`  // GHOSTBUG_ALLOW_HOST=staging.local opts specific non-production hosts in, like replay --allow-host.\n` +
`  const allowedHosts = (process.env.GHOSTBUG_ALLOW_HOST ?? '').split(',').map(host => host.trim().toLowerCase().replace(/^\\[|\\]$/g, '')).filter(Boolean);\n` +
`  const allowed = ['localhost', '127.0.0.1', '[::1]'].includes(base.hostname) || allowedHosts.includes(base.hostname.replace(/^\\[|\\]$/g, ''));\n` +
`  if (!['http:', 'https:'].includes(base.protocol) || !allowed || base.username || base.password) {\n` +
`    throw Error('GhostBug refuses to replay against a non-local URL. Set GHOSTBUG_BASE_URL=http://localhost:3000, or GHOSTBUG_ALLOW_HOST for a non-production host');\n` +
`  }\n` +
`  const target = new URL(startPath, base.origin);\n` +
`  const apiOrigins = new Set(recordedResponses.flatMap(fixture => fixture.origin ? [fixture.origin] : []));\n` +
`  const queue = new Map<string, GhostBugResponse[]>();\n` +
`  for (const fixture of recordedResponses) {\n` +
`    const key = fixture.method + ' ' + (fixture.origin ?? '') + fixture.path;\n` +
`    const matches = queue.get(key);\n` +
`    if (matches) matches.push(fixture); else queue.set(key, [fixture]);\n` +
`  }\n` +
`  // Same-origin requests without a fixture reach the app; recorded API origins only get fixtures; others are blocked.\n` +
`  await page.route('**/*', async route => {\n` +
`    const request = route.request();\n` +
`    const url = new URL(request.url());\n` +
`    const sameOrigin = url.origin === target.origin;\n` +
`    if (!sameOrigin && !apiOrigins.has(url.origin)) return route.abort('blockedbyclient');\n` +
`    const cors = sameOrigin ? {} : { headers: { 'access-control-allow-origin': target.origin, 'access-control-allow-credentials': 'true' } };\n` +
`    const matches = queue.get(request.method() + ' ' + (sameOrigin ? '' : url.origin) + url.pathname);\n` +
`    if (!matches) return sameOrigin ? route.continue() : route.fulfill({ status: 418, ...cors, body: 'GhostBug: no recorded response' });\n` +
(fingerprints
  ? `    // Prefer the fixture recorded for the same redacted query and body; otherwise keep recorded order.\n` +
    `    const fingerprint = fingerprintRequest(url.search, request.postData(), request.headers()['content-type']);\n` +
    `    const [fixture] = matches.splice(Math.max(0, matches.findIndex(f => fingerprint !== undefined && f.match === fingerprint)), 1);\n`
  : `    const fixture = matches.shift();\n`) +
`    if (!fixture) return route.fulfill({ status: 418, ...cors, body: 'GhostBug: fixture exhausted' });\n` +
`    return route.fulfill({ status: fixture.status, contentType: fixture.contentType, ...cors, body: fixture.body });\n` +
`  });\n` +
`  await page.goto(target.toString());\n` +
`  for (const action of actions) {\n` +
`    const element = page.locator(action.selector);\n` +
`    if (action.type === 'click') await element.click();\n` +
`    if (action.type === 'fill') {\n` +
`      if (action.value === ${toJson(REDACTED)}) throw Error('Replace [REDACTED] with safe test data in actions');\n` +
`      await element.fill(action.value);\n` +
`    }\n` +
`    if (action.type === 'check') {\n` +
`      if (action.checked) await element.check(); else await element.uncheck();\n` +
`    }\n` +
`  }\n` +
`  await expect(page.getByText(expectedText, { exact: false }).first()).toBeVisible({ timeout: 5000 });\n` +
`});\n` + (note ? `\n// Some input values were redacted; replace these before running the test.\n` : '');
}
