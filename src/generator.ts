import type { Recording } from './types.ts';
import { REDACTED } from './privacy.ts';

function toJson(value: unknown): string {
  // JSON serialization prevents captured user data from becoming executable code.
  return JSON.stringify(value, null, 2);
}

/** Emit an editable @playwright/test spec, without requiring an AI API key. */
export function generateSpec(recording: Recording, assertion?: string): string {
  const expectedText = assertion ?? recording.expect?.text;
  if (!expectedText?.trim()) throw Error('Missing expected outcome. Use --expect-text "Expected UI message"');
  const start = new URL(recording.startUrl);
  const path = start.pathname; // Intentionally discard query/hash; may include secrets.
  const note = recording.actions.some(a => a.type === 'fill' && a.value === REDACTED);
  return `// Auto-generated by GhostBug. Review the file and fixtures before sharing.\n` +
`// IMPORTANT: Run against a local/staging application, NOT production.\n` +
`import { test, expect } from '@playwright/test';\n\n` +
`const originalOrigin = ${toJson(start.origin)};\n` +
`const startPath = ${toJson(path)};\n` +
`type GhostBugAction = { type: 'click'; selector: string } | { type: 'fill'; selector: string; value: string } | { type: 'check'; selector: string; checked: boolean };\n` +
`type GhostBugResponse = { method: string; path: string; status: number; contentType: string; body: string };\n` +
`const actions: GhostBugAction[] = ${toJson(recording.actions)};\n` +
`const recordedResponses: GhostBugResponse[] = ${toJson(recording.network)};\n` +
`const expectedText = ${toJson(expectedText)};\n\n` +
`test(${toJson(recording.name)}, async ({ page }) => {\n` +
`  const baseUrl = process.env.GHOSTBUG_BASE_URL || originalOrigin;\n` +
`  const base = new URL(baseUrl);\n` +
`  if (!['http:', 'https:'].includes(base.protocol) || !['localhost', '127.0.0.1', '[::1]'].includes(base.hostname) || base.username || base.password) {\n` +
`    throw Error('GhostBug refuses to replay against a non-local URL. Set GHOSTBUG_BASE_URL=http://localhost:3000');\n` +
`  }\n` +
`  const target = new URL(startPath, base.origin);\n` +
`  const queue = new Map<string, typeof recordedResponses>();\n` +
`  for (const fixture of recordedResponses) {\n` +
`    const key = fixture.method + ' ' + fixture.path;\n` +
`    const matches = queue.get(key);\n` +
`    if (matches) matches.push(fixture); else queue.set(key, [fixture]);\n` +
`  }\n` +
`  await page.route('**/*', async route => {\n` +
`    const request = route.request();\n` +
`    const url = new URL(request.url());\n` +
`    if (url.origin !== target.origin) return route.abort('blockedbyclient');\n` +
`    const key = request.method() + ' ' + url.pathname;\n` +
`    const matched = queue.get(key);\n` +
`    if (matched) {\n` +
`      const fixture = matched.shift();\n` +
`      if (!fixture) return route.fulfill({ status: 418, body: 'GhostBug: fixture exhausted' });\n` +
`      return route.fulfill({ status: fixture.status, contentType: fixture.contentType, body: fixture.body });\n` +
`    }\n` +
`    return route.continue();\n` +
`  });\n` +
`  await page.goto(target.toString());\n` +
`  for (const action of actions) {\n` +
`    const element = page.locator(action.selector);\n` +
`    if (action.type === 'click') await element.click();\n` +
`    if (action.type === 'fill') {\n` +
`      if (action.value === ${toJson(REDACTED)}) throw Error('Replace [REDACTED] with safe test data in actions');\n` +
`      await element.fill(action.value);\n` +
`    }\n` +
`    if (action.type === 'check') {\n` +
`      if (action.checked) await element.check(); else await element.uncheck();\n` +
`    }\n` +
`  }\n` +
`  await expect(page.getByText(expectedText, { exact: false }).first()).toBeVisible({ timeout: 5000 });\n` +
`});\n` + (note ? `\n// Some input values were redacted; replace these before running the test.\n` : '');
}
